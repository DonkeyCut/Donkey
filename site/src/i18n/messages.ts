import type { Locale } from "@/i18n/locales";
import type { Messages, Namespace } from "@/i18n/namespaces";

type Loader<N extends Namespace> = () => Promise<{ default: Messages[N] }>;

/**
 * The given namespaces of one locale's catalog, keyed by namespace. Each file
 * is its own chunk, so a reader loads only the languages and namespaces it
 * asks for. Runs anywhere: the server, the page, the Bun engine and the worker.
 */
export async function loadMessages<N extends Namespace>(
  locale: Locale,
  namespaces: readonly N[],
): Promise<Pick<Messages, N>> {
  const entries = await Promise.all(
    namespaces.map(async (namespace) => {
      const mod = await (LOADERS[locale][namespace] as Loader<N>)();
      return [namespace, mod.default] as const;
    }),
  );
  return Object.fromEntries(entries) as Pick<Messages, N>;
}

